import re
src = open("app.py", encoding="utf-8-sig").read()

# 1. load .env and import auth helpers
if "import auth_utils" not in src:
    src = src.replace(
        "from datetime import datetime\n",
        "from datetime import datetime, timedelta\nfrom dotenv import load_dotenv\nload_dotenv()\nimport auth_utils\n",
        1,
    )

# 2. add otp_codes table creation inside init_auth_db
marker = "\n\ninit_auth_db()\n"
otp_sql = '''
    with get_db() as conn:
        if DATABASE_URL:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS otp_codes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email TEXT NOT NULL,
                    purpose TEXT NOT NULL,
                    otp_hash TEXT NOT NULL,
                    name TEXT,
                    password_hash TEXT,
                    expires_at TEXT NOT NULL,
                    attempts INTEGER NOT NULL DEFAULT 0,
                    created_at TEXT NOT NULL
                )
            """)
        else:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS otp_codes (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    email TEXT NOT NULL,
                    purpose TEXT NOT NULL,
                    otp_hash TEXT NOT NULL,
                    name TEXT,
                    password_hash TEXT,
                    expires_at TEXT NOT NULL,
                    attempts INTEGER NOT NULL DEFAULT 0,
                    created_at TEXT NOT NULL
                )
            """)
'''
if "otp_codes" not in src:
    src = src.replace(marker, "\n" + otp_sql + marker, 1)

# 3. fix the "(register)" typo in the public endpoints
src = src.replace('"(register)"', '"register"')

open("app.py", "w", encoding="utf-8").write(src)
print("app.py patched")
